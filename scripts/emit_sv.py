"""
emit_sv.py - writes the gate-level state machines of rtl/ from the minimised logic chosen in fsms.py, so the RTL is
exactly the logic the exploration scripts derive (two-level SOP / POS covers, SR / JK / D flip-flops).

  rtl/booth_ctrl_mealy.sv   rtl/booth_ctrl_moore.sv     Booth skip controllers (SR flip-flops, synchronous reset)
  rtl/seq_detector_sr.sv    rtl/seq_detector_jk.sv      composite 101 / 011 detector (SR / JK flip-flops)
  rtl/vending_fsm.sv        rtl/change_serializer.sv    vending machine balance FSM and change serializer (D FFs)

Resets are synchronous and sit in front of the flip-flops (S & ~rst, R | rst); they are not part of the gate counts.

usage: python3 scripts/emit_sv.py   (from the repository root)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from fsms import chosen  # noqa: E402
from logicmin import fcost  # noqa: E402

RTL = os.path.join(HERE, "..", "rtl")
CH = chosen()


def literal(var, positive, names):
    """names: variable -> (true expression, complement expression)"""
    t, c = names[var]
    return t if positive else c


def cover_expr(cover, sop, varnames, names):
    n = len(varnames)
    if not cover:
        return "1'b0" if sop else "1'b1"
    terms = []
    for v, care in cover:
        lits = []
        for j in range(n):
            bit = 1 << (n - 1 - j)
            if care & bit:
                pos = bool(v & bit)
                lits.append(literal(varnames[j], pos if sop else not pos, names))
        if len(lits) == 1:
            terms.append(lits[0])
        else:
            terms.append("(" + (" & " if sop else " | ").join(lits) + ")")
    return (" | " if sop else " & ").join(terms)


def header(title, fsm_name, lines):
    fsm, enc, ff, form, varnames, r = CH[fsm_name]
    rows = [f"//   {s:6s} = {''.join(map(str, c))}" for s, c in enc.items()]
    return ("// " + title + "\n// Generated by scripts/emit_sv.py from scripts/fsms.py - do not edit by hand.\n"
            f"// Flip-flops: {ff}, logic: minimal {form} (exact two-level minimisation with don't-cares),\n"
            f"// next-state {r['next_unshared']} two-input gates, outputs {r['out_unshared']} two-input gates.\n"
            "// State encoding:\n" + "\n".join(rows) + "\n" + "".join(f"// {l}\n" for l in lines))


def logic_block(fsm_name, names):
    fsm, enc, ff, form, varnames, r = CH[fsm_name]
    sop = form == "SOP"
    out = []
    for grp in ("next", "out"):
        for fn, (_, cover) in r[grp].items():
            out.append(f"  assign {fn.lower():6s} = {cover_expr(cover, sop, varnames, names)};"
                       f"  // {fcost(cover)} gates")
    return "\n".join(out)


def write(name, text):
    with open(os.path.join(RTL, name), "w", newline="\n") as f:
        f.write(text)
    print("wrote rtl/" + name)


def booth_ctrl(kind):
    name = f"{kind}Controller"
    fsm, enc, ff, form, varnames, r = CH[name]
    nb = len(next(iter(enc.values())))
    names = {f"Q{i}": (f"q[{i}]", f"qn[{i}]") for i in range(nb)}
    names.update({"X": ("shift_in", "~shift_in"), "C": ("completed", "~completed"),
                  "CS": ("current_shift", "~current_shift")})
    ports = ["  input  logic       clk,", "  input  logic       rst,           // synchronous, to INIT",
             "  input  logic       shift_in,      // " + ("multiplier bit 0 (the bit just entering the window)" if kind == "Mealy"
                                                       else "multiplier bit 1 (the next bit to enter the window)")]
    if kind == "Moore":
        ports.append("  input  logic       current_shift, // bit 0 of the value being loaded (selects S00 / S10 after INIT)")
    ports += ["  input  logic       completed,     // all shifts done: go to END",
              "  output logic [1:0] ex_op,         // 00 init, 01 add, 10 subtract, 11 shift",
              "  output logic       done" + ("," if kind == "Moore" else ""),]
    if kind == "Moore":
        ports.append("  output logic       init")
    sigs = sorted(set(fn.lower() for fn in r["next"]))
    body = [header(f"booth_ctrl_{kind.lower()}.sv - {kind} controller of the skip-capable Booth multiplier.", name,
                   ["EX_OP is a don't-care once COMPLETED is high (the datapath is frozen) and in END."]),
            f"module booth_ctrl_{kind.lower()} (", *ports, ");",
            f"  logic [{nb - 1}:0] q, qn;", f"  logic {', '.join(sigs)};", "  logic ex1, ex0;",
            logic_block(name, names), ""]
    for i in reversed(range(nb)):
        body.append(f"  sr_ff u_q{i} (.clk, .s(s{i} & ~rst), .r(r{i} | rst), .q(q[{i}]), .qn(qn[{i}]));")
    body += ["  assign ex_op = {ex1, ex0};", "endmodule", ""]
    text = "\n".join(body)
    # the output functions are named EX1 / EX0 / DONE / INIT in fsms.py
    write(f"booth_ctrl_{kind.lower()}.sv", text)


def detector(kind):
    name = f"{kind}CompositeDetector"
    fsm, enc, ff, form, varnames, r = CH[name]
    names = {f"Q{i}": (f"q[{i}]", f"qn[{i}]") for i in range(3)}
    names["X"] = ("x", "~x")
    a, b = ("s", "r") if kind == "SR" else ("j", "k")
    sigs = sorted(fn.lower() for fn in r["next"])
    body = [header(f"seq_detector_{kind.lower()}.sv - composite detector: Z1 = 101 always; Z2 = 011 until it fires, then "
                   "only Z1 until Z1 fires.", name,
                   ["8 states after minimising the 10-state composite machine; encoding chosen by prioritized adjacency",
                    "plus an exhaustive search over all 8! encodings (scripts/explore_detector.py)."]),
            f"module seq_detector_{kind.lower()} (", "  input  logic clk,", "  input  logic rst,   // synchronous, to S0",
            "  input  logic x,", "  output logic z1,", "  output logic z2", ");",
            "  logic [2:0] q, qn;", f"  logic {', '.join(sigs)};", logic_block(name, names), ""]
    ffmod = "sr_ff" if kind == "SR" else "jk_ff"
    for i in (2, 1, 0):
        body.append(f"  {ffmod} u_q{i} (.clk, .{a}({a}{i} & ~rst), .{b}({b}{i} | rst), .q(q[{i}]), .qn(qn[{i}]));")
    body += ["endmodule", ""]
    write(f"seq_detector_{kind.lower()}.sv", "\n".join(body))


def vending_fsm():
    name = "VendingFSM"
    fsm, enc, ff, form, varnames, r = CH[name]
    names = {"Q1": ("bal[1]", "~bal[1]"), "Q0": ("bal[0]", "~bal[0]"), "B1": ("bill[1]", "~bill[1]"),
             "B0": ("bill[0]", "~bill[0]")}
    body = [header("vending_fsm.sv - balance FSM of the vending machine (Mealy): price 4, bills 1 / 3 / 5.", name,
                   ["bill: 00 refund request, 01 = 1, 10 = 3, 11 = 5. item: 00 none, 01 one, 1X two.",
                    "change: amount to return (0..3). en = 0 freezes the state and suppresses every output."]),
            "module vending_fsm (", "  input  logic       clk,", "  input  logic       rst,       // synchronous, balance 0",
            "  input  logic       en,", "  input  logic [1:0] bill,", "  output logic [1:0] item,",
            "  output logic [1:0] change,", "  output logic [1:0] balance", ");",
            "  logic [1:0] bal;", "  logic d1, d0, ch1, ch0, rf1, rf0;", logic_block(name, names), "",
            "  always_ff @(posedge clk)", "    if (rst)     bal <= 2'b00;", "    else if (en) bal <= {d1, d0};", "",
            "  assign item    = {ch1, ch0} & {2{en}};", "  assign change  = {rf1, rf0} & {2{en}};",
            "  assign balance = bal;", "endmodule", ""]
    write("vending_fsm.sv", "\n".join(body))


def serializer():
    name = "ChangeSerializer"
    fsm, enc, ff, form, varnames, r = CH[name]
    names = {"Q1": ("owed[1]", "~owed[1]"), "Q0": ("owed[0]", "~owed[0]"), "C3": ("have3", "~have3")}
    body = [header("change_serializer.sv - pays the change one bill per clock: a 3-unit bill when 3 is owed and one is "
                   "available, otherwise 1-unit bills.", name,
                   ["State = amount still owed. load = 1 loads `amount` (the change of this cycle's purchase or refund).",
                    "bill_out: 00 none, 01 one-unit bill, 10 three-unit bill."]),
            "module change_serializer (", "  input  logic       clk,", "  input  logic       rst,",
            "  input  logic       load,", "  input  logic [1:0] amount,", "  input  logic       have3,     // a 3-unit bill is in the till",
            "  output logic [1:0] bill_out,", "  output logic       busy,",
            "  output logic [1:0] owed       // amount still to pay (the state)", ");",
            "  logic d1, d0, bo1, bo0;", logic_block(name, names), "",
            "  always_ff @(posedge clk)", "    if (rst)       owed <= 2'b00;", "    else if (load) owed <= amount;",
            "    else           owed <= {d1, d0};", "", "  assign bill_out = {bo1, bo0};", "endmodule", ""]
    write("change_serializer.sv", "\n".join(body))


if __name__ == "__main__":
    booth_ctrl("Mealy")
    booth_ctrl("Moore")
    detector("SR")
    detector("JK")
    vending_fsm()
    serializer()
